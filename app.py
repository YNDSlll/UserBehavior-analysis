"""
电商用户行为分析与流失预测 · Streamlit 可视化看板
====================================================
是什么：一个单页数据看板，把项目 M0~M4 的分析结果（指标、图表、模型）集中展示。
怎么跑：在项目根目录执行  streamlit run app.py  ，浏览器访问 http://localhost:8501
数据来源：output/app_data/ 目录下的预计算聚合 CSV（由 notebooks/M5_准备演示数据.py 生成）。
         App 本身不做任何重计算——"重活提前干、展示端只读结果"，保证页面秒开。
"""
from pathlib import Path

import pandas as pd
import streamlit as st

# ---------------------------------------------------------------
# 0. 页面全局配置（必须是第一个 st 调用）
#    page_title = 浏览器标签页标题；layout='wide' = 使用全屏宽度
# ---------------------------------------------------------------
st.set_page_config(page_title='电商用户行为分析', page_icon='📊', layout='wide')

# ---------------------------------------------------------------
# 1. 数据路径：基于本文件所在目录拼绝对路径
#    【修复点】原来写相对路径 'output/app_data'，
#    一旦不在项目根目录启动（如 streamlit run /全路径/app.py）就找不到数据。
#    Path(__file__) = 当前脚本文件的路径，.parent = 所在文件夹（项目根目录），
#    由此拼出的路径与启动位置无关，任何地方启动都能跑。
# ---------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent
APP_DATA = BASE_DIR / 'output' / 'app_data'

# ---------------------------------------------------------------
# 2. 数据读取函数（带缓存）
#    @st.cache_data 是 Streamlit 的缓存装饰器：
#    Streamlit 每次"用户交互/刷新"都会从头到尾重跑整个脚本（rerun 模型），
#    加了它，相同参数的读文件只执行一次，之后直接用内存里的结果 → 页面快。
#    index_col 参数：CSV 第一列是否当作行索引。
#    【修复点】原来所有文件统一 index_col=0，导致 kpis / funnel 这类
#    "没有索引列"的普通表第一列被误当索引，引发 KeyError。
#    现在每个文件显式声明自己的读法：需要日期/类目做行索引的传 0，
#    普通两列表传 None。
# ---------------------------------------------------------------
@st.cache_data
def load(name: str, index_col=0) -> pd.DataFrame:
    """读取 app_data 目录下的一个 CSV；index_col=None 表示不把任何列当行索引。"""
    return pd.read_csv(APP_DATA / name, index_col=index_col)

# 【修复点】启动时先检查数据目录是否存在，缺文件时给用户一句人话提示，
# 而不是甩出一整屏报错栈。（容错处理：错误要"可读"，报错信息是产品的一部分）
if not APP_DATA.exists():
    st.error('未找到演示数据目录 output/app_data/，请先运行 notebooks/M5_准备演示数据.py 生成数据。')
    st.stop()   # 终止页面渲染

# 逐个加载。注意两种读法的区别：
#   index_col=0  → 行索引是有意义的（日期、小时、分层名、特征名），图表用它当横轴/标签
#   index_col=None → 普通表格，全部当数据列
kpis            = load('kpis.csv', index_col=None)             # 顶部核心指标（两列：指标/数值）
daily           = load('daily.csv')                            # 按天：行为数、活跃用户数（索引=日期）
hourly          = load('hourly.csv')                           # 按小时：行为数（索引=0~23）
funnel          = load('funnel.csv', index_col=None)           # 转化漏斗（两列：环节/人数）
cluster_profile = load('cluster_profile.csv')                  # 用户分层画像（索引=分层名）
importance      = load('feature_importance.csv')['importance'].sort_values(ascending=False)
model_metrics   = load('model_metrics.csv', index_col=None)    # 模型对比（模型/AUC/召回率/F1）

# ---------------------------------------------------------------
# 3. 页头：标题 + 一句话项目简介
# ---------------------------------------------------------------
st.title('电商用户行为分析与流失预测')
st.caption('阿里天池 UserBehavior 数据集 · 100 万条采样 · 2017-11-25 ~ 12-03 · '
           '清洗 → EDA → RFM 分层 → 流失预测（随机森林 AUC 0.736）')

# ---------------------------------------------------------------
# 4. 核心指标卡（页面最上方一排大数字）
#    st.metric(标题, 数值) 是现成的指标卡组件。
#    【优化点】原来写死 6 列，指标数量一变就会静默丢失；
#    现在 len(kpis) 动态生成列数，加指标不用改代码。
# ---------------------------------------------------------------
metric_cols = st.columns(len(kpis))
for col, (_, row) in zip(metric_cols, kpis.iterrows()):
    col.metric(row['指标'], row['数值'])

# ---------------------------------------------------------------
# 5. 每日行为趋势（折线图）
#    daily 的行索引是日期，st.line_chart 自动把索引进度画成横轴。
#    两列（行为数 / 活跃用户数）会画成两条线并自动生成图例。
# ---------------------------------------------------------------
st.subheader('每日行为量与活跃用户数')
st.line_chart(daily)
st.caption('趋势整体上行，峰值出现在 12-02（周六），与双 12 预热节奏吻合；12-04 为不完整天已剔除。')

# ---------------------------------------------------------------
# 6. 左右双栏：小时分布 + 转化漏斗
#    st.columns(2) 把页面切成左右两半，with 块里的内容进入对应栏。
#    漏斗数据是"环节/人数"两列，先 set_index('环节') 让环节名做行索引，
#    st.bar_chart 才能把人数画成柱、环节名做横轴标签。
# ---------------------------------------------------------------
left, right = st.columns(2)
with left:
    st.subheader('小时活跃分布（北京时间）')
    st.bar_chart(hourly)
    st.caption('活跃高峰 19–22 点，建议将推送与秒杀安排在 19:30 前后。')
with right:
    st.subheader('转化漏斗（用户口径，9 天窗口）')
    st.bar_chart(funnel.set_index('环节'))
    st.caption('购买渗透率 68.9% 为"9 天内买过一次"的口径；单次行为转化率约 2.3%，与行业基准一致。')

# ---------------------------------------------------------------
# 7. 用户分层：柱状图（规模）+ 明细表（画像）
#    st.columns([2, 3]) 按比例分栏（2:3 宽度）。
#    st.dataframe 展示可排序、可滚动的交互表格。
# ---------------------------------------------------------------
st.subheader('RFM + K-Means 用户分层（K=4）')
c1, c2 = st.columns([2, 3])
with c1:
    st.bar_chart(cluster_profile['人数'])
    st.caption('各分层用户规模')
with c2:
    st.dataframe(cluster_profile, use_container_width=True)
st.caption('分层与流失标签交叉验证：早期沉睡用户流失率 100%，聚类结果与预测标签高度一致。'
           'M 用"购买商品种类数"替代金额（数据集无金额字段），F 与 M 相关系数 0.979，价值维度实为综合购买强度。')

# ---------------------------------------------------------------
# 8. 流失预测模型：对比表 + 特征重要性
#    【修复点】模型指标原来硬编码在这里，M4 重跑后会失同步；
#    现在读 model_metrics.csv，与分析脚本共用同一份数据（单一数据源）。
#    st.table 是静态表格（不可排序），适合这种几行的定版对比。
# ---------------------------------------------------------------
st.subheader('流失预测模型')
m1, m2 = st.columns(2)
with m1:
    st.markdown('**模型对比**（测试集 25%，分层抽样）')
    metrics_tbl = model_metrics.set_index('模型')
    st.table(metrics_tbl)
with m2:
    st.markdown('**特征重要性（随机森林）**')
    st.bar_chart(importance)
st.caption('关键发现：前 6 天购买次数（buy_count）是后 3 天去留的最强信号；'
           '且早期买得多与流失呈正向关系——存在"囤货型"用户，购后即流失，'
           '这类非线性关系正是树模型显著优于逻辑回归的原因。')

# ---------------------------------------------------------------
# 9. 结论与业务建议
# ---------------------------------------------------------------
st.subheader('结论与业务建议')
st.markdown(
    """
1. **流量节奏**：观察期整体上行，周末与大促预热叠加，运营资源应对齐大促节奏逐步加码；
2. **触达时机**：活跃高峰 19–22 点，推送/秒杀/直播安排在 19:30 前后收益最大；
3. **人群运营**：30% 的早期沉睡用户流失率 100%，应作为召回优先级最高的人群；
4. **预测落地**：随机森林模型（AUC 0.736）可圈出高流失风险用户，挽留预算优先投放高召回命中人群；
5. **方法论局限**：数据仅 9 天，流失定义按窗口 1/3（3 天）设定；采样为文件顺序前 100 万行（已验证人均行为数与全量一致）。
    """)
